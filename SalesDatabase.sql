-- =====================================================================
-- VIEW: SalesSummary - convenient overall sales info per customer
-- =====================================================================
CREATE OR ALTER VIEW dbo.vw_SalesSummary AS
SELECT
    cm.CustomerID,
    cm.CustomerName,
    COUNT(DISTINCT i.InvoiceID)      AS TotalInvoices,
    SUM(id.Quantity)                 AS TotalUnitsPurchased,
    SUM(id.LineTotal)                AS TotalSalesAmount
FROM dbo.CustomerMaster cm
LEFT JOIN dbo.Invoice i          ON i.CustomerID = cm.CustomerID
LEFT JOIN dbo.InvoiceDetails id  ON id.InvoiceID = i.InvoiceID
GROUP BY cm.CustomerID, cm.CustomerName;
GO

