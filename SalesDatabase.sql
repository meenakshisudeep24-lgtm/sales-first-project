-- =====================================================================
-- TABLE: CustomerMaster
-- =====================================================================
CREATE TABLE dbo.CustomerMaster (
    CustomerID      INT             NOT NULL PRIMARY KEY,
    CustomerName    NVARCHAR(100)   NOT NULL,
    ContactName     NVARCHAR(100)   NULL,
    Address         NVARCHAR(200)   NULL,
    City            NVARCHAR(50)    NULL,
    State           NVARCHAR(50)    NULL,
    PostalCode      VARCHAR(10)     NULL,
    Country         NVARCHAR(50)    NULL,
    Phone           VARCHAR(20)     NULL,
    Email           NVARCHAR(100)   NULL,
    RegisteredDate  DATE            NULL
);
GO

-- =====================================================================
-- TABLE: ProductMaster
-- =====================================================================
CREATE TABLE dbo.ProductMaster (
    ProductID       INT             NOT NULL PRIMARY KEY,
    ProductName     NVARCHAR(100)   NOT NULL,
    Category        NVARCHAR(50)    NULL,
    UnitPrice       DECIMAL(10,2)   NOT NULL,
    StockQty        INT             NOT NULL DEFAULT 0,
    Supplier        NVARCHAR(100)   NULL
);
GO

-- =====================================================================
-- TABLE: SalesPersonMaster
-- =====================================================================
CREATE TABLE dbo.SalesPersonMaster (
    SalesPersonID   INT             NOT NULL PRIMARY KEY,
    SalesPersonName NVARCHAR(100)   NOT NULL,
    Region          NVARCHAR(50)    NULL,
    HireDate        DATE            NULL
);
GO

-- =====================================================================
-- TABLE: Invoice
-- =====================================================================
CREATE TABLE dbo.Invoice (
    InvoiceID       INT             NOT NULL PRIMARY KEY,
    CustomerID      INT             NOT NULL,
    SalesPersonID   INT             NULL,
    InvoiceDate     DATE            NOT NULL,
    TotalAmount     DECIMAL(12,2)   NOT NULL,
    PaymentStatus   VARCHAR(20)     NOT NULL DEFAULT 'Pending',
    CONSTRAINT FK_Invoice_Customer FOREIGN KEY (CustomerID) REFERENCES dbo.CustomerMaster(CustomerID),
    CONSTRAINT FK_Invoice_SalesPerson FOREIGN KEY (SalesPersonID) REFERENCES dbo.SalesPersonMaster(SalesPersonID)
);
GO

-- =====================================================================
-- TABLE: InvoiceDetails (Sales Info - line items per invoice)
-- =====================================================================
CREATE TABLE dbo.InvoiceDetails (
    SalesInfoID     INT             NOT NULL PRIMARY KEY,
    InvoiceID       INT             NOT NULL,
    ProductID       INT             NOT NULL,
    Quantity        INT             NOT NULL,
    UnitPrice       DECIMAL(10,2)   NOT NULL,
    DiscountPct     DECIMAL(5,2)    NOT NULL DEFAULT 0,
    LineTotal       DECIMAL(12,2)   NOT NULL,
    CONSTRAINT FK_InvoiceDetails_Invoice FOREIGN KEY (InvoiceID) REFERENCES dbo.Invoice(InvoiceID),
    CONSTRAINT FK_InvoiceDetails_Product FOREIGN KEY (ProductID) REFERENCES dbo.ProductMaster(ProductID)
);
GO

